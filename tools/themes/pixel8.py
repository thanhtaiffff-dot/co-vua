def sprite(shape, color, scale=10, frame=16):
    h, w = len(shape), len(shape[0])
    fill = [[c in '#x' for c in row] for row in shape]
    mark = [[c == 'x' for c in row] for row in shape]
    img = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    px = img.load()
    for y in range(h):
        for x in range(w):
            if fill[y][x]:
                left = x > 0 and fill[y][x - 1]
                right = x < w - 1 and fill[y][x + 1]
                up = y > 0 and fill[y - 1][x]
                down = y < h - 1 and fill[y + 1][x]
                if color == 'w':
                    c = PAL['L0']
                    if not right or (x < w - 2 and not fill[y][x + 2] and not up): c = PAL['L1']
                    if not down and y < h - 1: c = PAL['L1']
                else:
                    c = PAL['L3']
                    if not left or not up: c = PAL['L2']
                    if (not left and not up): c = PAL['L1']
                if mark[y][x]: c = PAL['L3'] if color == 'w' else PAL['L1']
                px[x, y] = c + (255,)
            else:
                near = any(0 <= y + dy < h and 0 <= x + dx < w and fill[y + dy][x + dx]
                           for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                if near: px[x, y] = PAL['L3'] + (255,)
    return img.resize((w * scale, h * scale), Image.NEAREST)


def board(scale=8):
    img = Image.new('RGB', (128, 128))
    px = img.load()
    for y in range(128):
        for x in range(128):
            sx, sy = x // 16, y // 16
            dark = (sx + sy) % 2 == 1
            lx, ly = x % 16, y % 16
            c = PAL['L2'] if dark else PAL['L1']
            # Ô sáng có viền trong một điểm sáng hơn ở trên trái, ô tối có chấm hoa văn thưa.
            if not dark and (lx == 0 or ly == 0): c = (160, 208, 136)
            if dark and (lx + ly * 3) % 8 == 0 and lx % 4 == 1 and ly % 4 == 1: c = (44, 90, 74)
            px[x, y] = c
    return img.resize((128 * scale, 128 * scale), Image.NEAREST)


